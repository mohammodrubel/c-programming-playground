#include <stdio.h>  // ইনপুট নেওয়া ও আউটপুট দেখানোর জন্য

int main()
{
    int n;  // Array-তে কয়টি সংখ্যা থাকবে, তা রাখব
    scanf("%d", &n);  // ব্যবহারকারীর কাছ থেকে n-এর মান নেব

    int a[n];  // n সংখ্যক উপাদান রাখার জন্য Array তৈরি করলাম

    for (int i = 0; i < n; i++)  // Array-এর প্রতিটি ঘরে সংখ্যা নেওয়ার Loop
    {
        scanf("%d", &a[i]);  // Array-এর i নম্বর Index-এ সংখ্যা রাখব
    }

    int frequently[6] = {0};  // 0 থেকে 5 পর্যন্ত প্রতিটি সংখ্যার গণনা শুরুতে 0

    for (int i = 0; i < n; i++)  // Array-এর প্রতিটি সংখ্যা পরীক্ষা করব
    {
        frequently[a[i]]++;  // যে সংখ্যা পাব, তার Frequency 1 বাড়াব
    }

    for (int i = 0; i < 6; i++)  // 0 থেকে 5 পর্যন্ত প্রতিটি সংখ্যার জন্য Loop
    {
        printf("%d -> %d\n", i, frequently[i]);  // সংখ্যা ও সেটি কতবার এসেছে দেখাব
    }

    return 0;  // প্রোগ্রাম শেষ করব
}